"""GitHub-only maintenance checks against disposable real PostgreSQL.

Rows contain generated bytes. No production credentials, logs, services, or
paid API requests are used. Only metadata evidence is printed.
"""

import datetime
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import threading
import time

if os.environ.get("GITHUB_ACTIONS") != "true":
    raise SystemExit("This rehearsal runs only in GitHub Actions")

repo = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location(
    "cleanup", repo / "deploy/maintenance/conversation_logs_cleanup.py")
cleanup = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cleanup)
cleanup.MAX_BYTES = 5 * 1024**2
cleanup.TARGET_BYTES = 3 * 1024**2
cleanup.BODY_BUDGET_BYTES = int(2.5 * 1024**2)
cleanup.REWRITE_RESERVE_BYTES = 1024**2
cleanup.MIN_FREE_BYTES = 0
cleanup.DATA_DIR = tempfile.gettempdir()
cleanup.LOG_FILE = Path(tempfile.gettempdir()) / "cleaner-metadata.jsonl"
events = []
cleanup.log = lambda event, **metadata: events.append({"event": event, **metadata})


def psql(statement):
    process = subprocess.run(
        ["docker", "exec", "sub2api-postgres", "psql", "-X", "-qAt",
         "-v", "ON_ERROR_STOP=1", "-U", "fixture", "-d", "cleanup", "-c", statement],
        capture_output=True, text=True, timeout=30)
    if process.returncode:
        raise RuntimeError("isolated PostgreSQL operation failed")
    return process.stdout.strip()


psql("""
CREATE TABLE conversation_logs (
  id bigserial PRIMARY KEY, created_at timestamptz NOT NULL,
  completed_at timestamptz, status text NOT NULL,
  request_body text NOT NULL, response_body text NOT NULL
);
ALTER TABLE conversation_logs ALTER COLUMN request_body SET STORAGE EXTERNAL;
ALTER TABLE conversation_logs ALTER COLUMN response_body SET STORAGE EXTERNAL;
INSERT INTO conversation_logs(created_at,completed_at,status,request_body,response_body)
SELECT now()-interval '1 day' + i*interval '1 second',
       now()-interval '1 hour', 'completed',
       (SELECT string_agg(md5((j+i*1000)::text),'') FROM generate_series(1,1024) j),
       (SELECT string_agg(md5((j+i*3000)::text),'') FROM generate_series(1,512) j)
FROM generate_series(1,200) i;
INSERT INTO conversation_logs(created_at,completed_at,status,request_body,response_body)
VALUES(now(),NULL,'pending','pending generated bytes','');
""")
assert cleanup.relation()["physical_bytes"] > cleanup.MAX_BYTES
pending_id = int(psql("SELECT id FROM conversation_logs WHERE status='pending'"))
cleanup.run()
first = cleanup.relation()
assert first["stored_bytes"] < cleanup.TARGET_BYTES, first
assert int(psql(f"SELECT count(*) FROM conversation_logs WHERE id={pending_id}")) == 1
assert any(e["event"] == "physical_rewrite_deferred_busy" for e in events)
assert not any(e["event"] == "physical_rewrite_start" for e in events)
print(json.dumps({"scenario": "busy retention", "passed": True, "metadata": first}))

psql("UPDATE conversation_logs SET status='completed',completed_at=now()-interval '1 hour',created_at=now()-interval '1 day'")
assert cleanup.guarded_rewrite() is True
compacted = cleanup.relation()
assert compacted["physical_bytes"] < cleanup.TARGET_BYTES, compacted
print(json.dumps({"scenario": "idle physical recovery", "passed": True,
                  "metadata": compacted}))

# An isolated session holding ACCESS EXCLUSIVE with the maintenance identity
# exercises the same blocking relationship used by VACUUM FULL. This avoids
# manufacturing hundreds of MB merely to keep a rewrite alive long enough.
original_command = cleanup.sql_command


def held_rewrite(statement, **options):
    if statement.startswith("VACUUM (FULL"):
        statement = "BEGIN; LOCK TABLE conversation_logs IN ACCESS EXCLUSIVE MODE; SELECT pg_sleep(10); COMMIT;"
    return original_command(statement, **options)


cleanup.sql_command = held_rewrite
original_cancel = cleanup.cancel_rewrite


def cancel_held_rewrite():
    cleanup.sql("""
      SELECT json_build_object('cancelled', count(*)) FROM (
        SELECT pg_cancel_backend(pid) FROM pg_stat_activity
        WHERE pid<>pg_backend_pid()
          AND application_name='sub2api-conversation-cleanup'
          AND state='active' AND query ILIKE 'BEGIN%'
      ) t
    """, fast=True)


cleanup.cancel_rewrite = cancel_held_rewrite
outcome = {}
thread = threading.Thread(target=lambda: outcome.update(result=cleanup.guarded_rewrite()))
thread.start()
deadline = time.monotonic() + 5
while time.monotonic() < deadline:
    if int(psql("SELECT count(*) FROM pg_stat_activity WHERE application_name='sub2api-conversation-cleanup' AND query ILIKE 'BEGIN%' AND state='active'")):
        break
    time.sleep(0.05)
else:
    raise AssertionError("isolated maintenance lock was not established")
started = time.monotonic()
psql("SET statement_timeout='4s'; INSERT INTO conversation_logs(created_at,completed_at,status,request_body,response_body) VALUES(now(),NULL,'pending','new request','');")
wait = time.monotonic() - started
thread.join(timeout=5)
assert not thread.is_alive()
assert outcome["result"] is False
assert wait < 4, wait
assert any(e["event"] == "physical_rewrite_cancelled_for_requests" for e in events)
cleanup.sql_command = original_command
cleanup.cancel_rewrite = original_cancel
print(json.dumps({"scenario": "new request cancels maintenance lock", "passed": True,
                  "request_wait_seconds": round(wait, 3)}))
print(json.dumps({"scope": "real disposable PostgreSQL; reduced thresholds and generated bodies",
                  "production_requests": 0, "events": events}, ensure_ascii=False))
